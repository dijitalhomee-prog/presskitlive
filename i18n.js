let currentLang = localStorage.getItem('presskit_lang') || 'tr';

function getTranslation(key, defaultText) {
  if (i18nTranslations[currentLang] && i18nTranslations[currentLang][key]) {
    return i18nTranslations[currentLang][key];
  }
  return defaultText || key;
}

function setLanguage(lang) {
  if (lang !== 'tr' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('presskit_lang', lang);

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Update all elements with data-i18n attribute safely without erasing icons
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18nTranslations[lang] && i18nTranslations[lang][key]) {
      const text = i18nTranslations[lang][key];
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        // Check if element has child text nodes specifically to preserve child <i> or <svg> icons
        let textUpdated = false;
        for (let i = 0; i < el.childNodes.length; i++) {
          const node = el.childNodes[i];
          if (node.nodeType === 3 && node.nodeValue.trim().length > 0) { // Node.TEXT_NODE
            node.nodeValue = " " + text;
            textUpdated = true;
            break;
          }
        }
        if (!textUpdated) {
          // If no existing text node found or element is simple span/div
          if (el.children.length === 0) {
            el.innerText = text;
          } else {
            // Append text node safely
            const textNode = document.createTextNode(" " + text);
            el.appendChild(textNode);
          }
        }
      }
    }
  });

  // Update all elements with data-i18n-html attribute (for HTML formatted strings)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (i18nTranslations[lang] && i18nTranslations[lang][key]) {
      el.innerHTML = i18nTranslations[lang][key];
    }
  });

  // Update language toggle buttons active state
  document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  if (window.lucide) {
    try { lucide.createIcons(); } catch(e) {}
  }

  // Trigger custom event if page scripts need re-render
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: lang } }));
}

function initI18n() {
  setLanguage(currentLang);
}

// Global Exports
window.setLanguage = setLanguage;
window.getTranslation = getTranslation;
window.initI18n = initI18n;

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
window.addEventListener('load', initI18n);
